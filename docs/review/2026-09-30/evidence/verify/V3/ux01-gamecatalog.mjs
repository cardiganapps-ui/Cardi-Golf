// UX-01 scope: the game-options sheet shared by the wizard and Comité › Torneo (GameCatalog.tsx:125).
import { launch, phone, BASE, sleep, logTo, focused, sheetValues } from './lib.mjs'
const log = logTo('ux01-typing.log')
const b = await launch()
const { ctx, page } = await phone(b)
await page.goto(`${BASE}/t/_/friends8/admin/torneo`, { waitUntil: 'domcontentloaded' })
await sleep(2000)
await page.locator('main [role=tab], main [role=radio], main button').filter({ hasText: /^Juegos$/ }).first().tap()
await sleep(800)
const more = page.getByRole('button', { name: 'Más opciones' })
const n = await more.count()
if (!n) { log(JSON.stringify({ name: 'I gamecatalog', error: 'no «Más opciones» button on /t/_/friends8/admin/torneo' })); await b.close(); process.exit(0) }
await more.first().scrollIntoViewIfNeeded()
await more.first().tap()
await page.locator('[role=dialog]').last().waitFor()
await sleep(250)
const opened = await focused(page)
const input = page.locator('[role=dialog]').last().locator('input.input').first()
const bb = await input.boundingBox()
await page.touchscreen.tap(bb.x + bb.width / 2, bb.y + bb.height / 2)
await sleep(120)
await page.keyboard.press('Control+A')
const steps = []; for (const ch of 'Skins del sabado') { await page.keyboard.type(ch); await sleep(150); steps.push((await sheetValues(page))[0] + ' @' + (await focused(page)).slice(0, 22)) }; console.log(JSON.stringify(steps))
log(JSON.stringify({ name: 'I gamecatalog label (Comité › Torneo, friends8)', buttons: n, openedWithFocus: opened, values: await sheetValues(page), focus: await focused(page) }))
await b.close()
