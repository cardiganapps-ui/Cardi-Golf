import { launch, phone, BASE, sleep, log } from './lib.mjs'
const b = await launch()
const ctx = await phone(b, { blockSupabase: true })
const p = await ctx.newPage()
await p.goto(`${BASE}/t/_/full12-live/admin/jugadores`, { waitUntil: 'networkidle' })
await sleep(400)
await p.locator('[class*="rowBtn"]').nth(2).tap()
await sleep(400)
const btn = p.getByRole('button', { name: /Amarrar perfil/ })
await btn.scrollIntoViewIfNeeded()
await btn.tap()
await sleep(500)
const dialogs = p.getByRole('dialog')
const n = await dialogs.count()
const inner = dialogs.nth(n - 1)
const inp = inner.locator('input').first()
await inp.tap()
for (const ch of 'Camilo') { await p.keyboard.type(ch); await sleep(150) }
log('sheet-focus3', JSON.stringify({ sheet: 'Jugadores › Editar › Amarrar perfil (nested sheet): type "Camilo"', dialogs: n, value: await inp.inputValue(), active: await p.evaluate(() => document.activeElement?.tagName + (document.activeElement?.getAttribute('role') ? '[' + document.activeElement.getAttribute('role') + ']' : '')) }))
await b.close()
