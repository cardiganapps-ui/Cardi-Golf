import { launch, phone, BASE, shot, sleep, measureTargets } from './lib.mjs'
const b = await launch()
const ctx = await phone(b, { blockSupabase: true })
const p = await ctx.newPage()
await p.goto(`${BASE}/t/_/full12-live/tarjeta`, { waitUntil: 'networkidle' })
await p.locator('text=Guardar hoyo').waitFor()
const rows = p.locator('[class*="player_"]').filter({ has: p.locator('[role="group"]') })
// two 3-putts: row 2 and row 4 putts +1
await rows.nth(1).locator('[role="group"]').nth(1).locator('button').nth(1).tap()
await rows.nth(3).locator('[role="group"]').nth(1).locator('button').nth(1).tap()
await p.getByRole('button', { name: 'Guardar hoyo' }).tap()
await p.getByText('¿Quién embocó al último?').waitFor()
await sleep(900)
console.log(await shot(p, 't_tarjeta-full12-live-15pro-light-ux-tiebreak-settled.png'))
const dlg = p.getByRole('dialog')
console.log('dialog box', JSON.stringify(await dlg.boundingBox()))
const t = await measureTargets(p, { scope: '[role="dialog"]' })
console.log(JSON.stringify(t, null, 0))
// Close it: does the hole save? (it should not)
await p.getByRole('button', { name: 'Cerrar' }).tap()
await sleep(400)
console.log('hole after close:', await p.locator('[class*="holeNum"]').textContent())
// Try swiping on the tiebreak sheet (audit P1 19): reopen and drag horizontally inside it
await p.getByRole('button', { name: 'Guardar hoyo' }).tap()
await p.getByText('¿Quién embocó al último?').waitFor()
await sleep(500)
const box = await dlg.boundingBox()
const cdp = await ctx.newCDPSession(p)
const y = box.y + 60
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 300, y }] })
for (let i = 1; i <= 10; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 300 - i * 20, y }] })
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
await sleep(400)
console.log('hole after swipe inside sheet:', await p.locator('[class*="holeNum"]').textContent(), 'sheet open:', await p.getByText('¿Quién embocó al último?').isVisible())
await b.close()
