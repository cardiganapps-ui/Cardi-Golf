// Fix a wrong score from Comité › Tarjetas (fixture full12-live): pick player, hole, change, save; and the inbox.
import { launch, phone, BASE, Journey, saveJson, shot, sleep, log } from './lib.mjs'
const b = await launch()
const out = {}
const ctx = await phone(b, { blockSupabase: true })
const p = await ctx.newPage()
await p.goto(`${BASE}/t/_/full12-live/mas`, { waitUntil: 'networkidle' })
await sleep(500)
const j = new Journey('fix-score-comite', p)
await j.tap(p.getByRole('link', { name: /Comité/ }).first(), 'Más › Consola del Comité', () => p.getByText('Comité').first().waitFor())
await sleep(400)
await j.tap(p.getByRole('link', { name: /Tarjetas/ }).first(), 'Tarjetas tab', () => sleep(500))
await shot(p, 't_admin_scores-full12-live-15pro-light-ux-inbox.png')
await shot(p, 't_admin_scores-full12-live-15pro-light-ux-inbox-full.png', { fullPage: true })
out.inboxText = (await p.evaluate(() => document.body.innerText)).slice(0, 1800)
const sel = p.locator('select').first()
const opts = await sel.evaluate((s) => [...s.options].map((o) => ({ v: o.value, t: o.text })))
out.playerOptions = opts.length
j.scroll('scroll to the player picker')
await j.tap(sel, 'player select (OS picker)')
await sel.selectOption(opts[3].v)
j.taps++
j.steps.push({ kind: 'tap', label: 'choose player in OS picker' })
await sleep(400)
j.scroll('scroll to the hole grid')
const tile = p.locator('[class*="holes"] button').nth(4)
await j.tap(tile, 'hole 5 tile', () => p.getByRole('dialog').waitFor())
const inp = p.getByRole('dialog').locator('input').first()
await j.type(inp, '6', 'strokes 6 (one digit)', { clear: true })
out.sheetText = (await p.getByRole('dialog').innerText()).slice(0, 400)
await j.tap(p.getByRole('dialog').getByRole('button', { name: /Guardar/ }), 'Guardar', () => sleep(600))
out.toast = await p.locator('[class*="toaster"]').allTextContents()
out.fix = j.summary()
log('comite-fix', `taps=${out.fix.taps} keys=${out.fix.keystrokes} players=${out.playerOptions} toast=${JSON.stringify(out.toast)}`)
saveJson('comite-fix', out)
await b.close()
