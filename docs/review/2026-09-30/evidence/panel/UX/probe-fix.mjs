import { launch, phone, BASE, sleep, shot } from './lib.mjs'
const b = await launch()
const ctx = await phone(b, { blockSupabase: true })
const p = await ctx.newPage()
await p.goto(`${BASE}/t/_/full12-live/tarjeta`, { waitUntil: 'networkidle' })
await p.getByRole('button', { name: 'Guardar hoyo' }).waitFor()
await p.getByRole('button', { name: 'Ver tarjeta' }).tap()
await p.locator('table').waitFor()
await p.locator('table button', { hasText: /^9$/ }).tap()
await sleep(500)
console.log('hole', await p.locator('[class*="holeNum"]').textContent())
const row1 = p.locator('[class*="player_"]').filter({ has: p.locator('[role="group"]') }).first()
const s = row1.locator('[role="group"]').first()
console.log('strokes', await s.locator('[aria-live]').textContent())
await s.locator('button').nth(1).tap()
await sleep(300)
console.log('strokes after +', await s.locator('[aria-live]').textContent())
const btns = await p.getByRole('button').allTextContents()
console.log('buttons', JSON.stringify(btns.filter((x) => /Guardar/.test(x))))
await p.getByRole('button', { name: /Guardar/ }).first().tap()
await sleep(800)
console.log('hole after save', await p.locator('[class*="holeNum"]').textContent().catch(() => 'n/a'), 'dialog', await p.getByRole('dialog').innerText().catch(() => 'none'))
console.log('toasts', await p.locator('[aria-live="polite"]').allTextContents())
await shot(p, 't_tarjeta-full12-live-15pro-light-ux-fix-after-save.png')
await b.close()
