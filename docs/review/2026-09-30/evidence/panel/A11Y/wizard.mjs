import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
await page.goto('http://127.0.0.1:4173/organizer/nuevo/_', { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
const info = () => page.evaluate(() => { const a = document.activeElement; return { tag: a?.tagName, text: (a?.getAttribute('aria-label') ?? a?.textContent ?? '').trim().slice(0, 40), h: [...document.querySelectorAll('h1,h2')].map(h => h.tagName + ':' + h.textContent.trim().slice(0, 30)).slice(0, 4), steps: [...document.querySelectorAll('[aria-current], ol li, [class*="step"]')].slice(0, 6).map(e => (e.getAttribute('aria-current') ?? '') + ':' + e.textContent.trim().slice(0, 20)) } })
await page.locator('input').first().fill('Copa de prueba')
const next = page.getByRole('button', { name: /siguiente|continuar/i }).last()
await next.focus()
console.log('before', JSON.stringify(await info()))
await page.keyboard.press('Enter')
await page.waitForTimeout(700)
console.log('after step 2', JSON.stringify(await info()))
await browser.close()
