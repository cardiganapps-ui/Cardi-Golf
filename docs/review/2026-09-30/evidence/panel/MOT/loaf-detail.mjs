import { launch, ctx, BASE, load, throttle } from './lib.mjs'
const b = await launch()
const c = await ctx(b, '15pro')
await c.addInitScript(`window.__lo=[];new PerformanceObserver(l=>{for(const e of l.getEntries())window.__lo.push({start:Math.round(e.startTime),d:Math.round(e.duration),block:Math.round(e.blockingDuration),render:Math.round(e.renderStart-e.startTime),style:Math.round(e.styleAndLayoutStart-e.startTime),scripts:e.scripts.map(s=>({inv:s.invoker,type:s.invokerType,d:Math.round(s.duration),fl:Math.round(s.forcedStyleAndLayoutDuration),src:(s.sourceURL||'').split('/').pop()+':'+s.sourceFunctionName}))})}).observe({type:'long-animation-frame',buffered:true})`)
const p = await c.newPage()
await p.goto(BASE + '/t/_/full12-live', { waitUntil: 'networkidle' })
await p.waitForTimeout(1500)
await throttle(p, 4)
await p.evaluate(() => { window.__lo = [] })
console.log('load', load())
await p.getByRole('radio', { name: 'Gross' }).click()
await p.waitForTimeout(1200)
console.log(JSON.stringify(await p.evaluate(() => window.__lo), null, 1))
await b.close()
