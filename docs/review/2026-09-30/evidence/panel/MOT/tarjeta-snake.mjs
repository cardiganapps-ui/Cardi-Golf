import { launch, ctx, BASE } from './lib.mjs'
const b = await launch()
const c = await ctx(b, '15pro')
const p = await c.newPage()
await p.goto(BASE + '/t/_/full12-live/tarjeta', { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
const row = p.locator('[class*="player_"]', { hasText: 'Iván' }).first()
await row.getByRole('button', { name: 'Putts: más' }).click()
console.log('putts now', await row.locator('[role="group"][aria-label="Putts"] [aria-live]').textContent())
await p.getByRole('button', { name: /^Guardar hoyo/ }).click()
await p.waitForTimeout(600)
const txt = await p.evaluate(() => document.body.innerText)
console.log('mentions víbora/serpiente on Tarjeta after save:', /v[íi]bora|serpiente/i.test(txt), '| toast:', await p.evaluate(() => document.querySelector('[class*="toast"] span')?.textContent))
await p.getByRole('link', { name: 'Juegos' }).click(); await p.waitForTimeout(600)
await p.getByRole('button', { name: /Víbora/ }).first().click(); await p.waitForTimeout(600)
const g = await p.evaluate(() => [...document.querySelectorAll('[class*="group_"]')].map((x) => (x.closest('section')?.querySelector('h3')?.textContent || '') + ' ' + x.querySelector('strong')?.textContent + ': ' + (x.querySelector('ol li:last-child')?.textContent || '')).join(' / '))
console.log('Juegos › Víbora:', g)
await b.close()
