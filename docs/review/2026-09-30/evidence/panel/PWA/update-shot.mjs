import { launch, SHOTS } from './lib.mjs'
import fs from 'node:fs'
const SW = 'site/sw.js'
const orig = fs.readFileSync('sw.orig.js', 'utf8')
fs.writeFileSync(SW, orig)
const b = await launch()
const ctx = await b.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const cdp = await ctx.newCDPSession(page)
await cdp.send('Emulation.setSafeAreaInsetsOverride', { insets: { top: 59, bottom: 34, left: 0, right: 0 } })
await page.goto('http://127.0.0.1:4193/t/_/full12-live/tarjeta')
await page.evaluate(() => navigator.serviceWorker.ready)
await page.reload({ waitUntil: 'load' }); await page.getByRole('button', { name: 'Guardar hoyo' }).waitFor()
await page.waitForTimeout(4000)
fs.writeFileSync(SW, orig.replace(/("index\.html",revision:")[0-9a-f]+/, '$1bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb'))
await page.getByRole('button', { name: /: más$/ }).first().tap()
await page.evaluate(async () => { await (await navigator.serviceWorker.getRegistration()).update() })
await page.waitForFunction(async () => !!(await navigator.serviceWorker.getRegistration())?.waiting, null, { timeout: 30000 })
await page.waitForTimeout(1000)
await page.getByRole('button', { name: 'Guardar hoyo' }).tap()
await page.waitForTimeout(450)
await page.screenshot({ path: `${SHOTS}/t_tarjeta-full12-live-15pro-light-pwa-update-toast-stack.png` })
const boxes = await page.locator('[role=status]').evaluateAll(els => els.map(e => { const r = e.getBoundingClientRect(); return [e.textContent.trim().slice(0, 40), Math.round(r.top), Math.round(r.bottom)] }))
console.log(JSON.stringify(boxes), 'save button', JSON.stringify(await page.getByRole('button', { name: 'Guardar hoyo' }).boundingBox()))
fs.writeFileSync(SW, orig)
await b.close()
