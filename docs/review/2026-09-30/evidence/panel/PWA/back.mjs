import { launch } from './lib.mjs'
const b = await launch()
const ctx = await b.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const base = 'http://127.0.0.1:4173/t/_/full12-live'
// 1) a sheet open + system back
await page.goto('http://127.0.0.1:4173/fixture', { waitUntil: 'networkidle' })
await page.goto(base, { waitUntil: 'networkidle' })
await page.locator('button[aria-label*="Camilo"]').first().click()
await page.getByRole('dialog').waitFor()
console.log('1. player sheet open at', new URL(page.url()).pathname)
await page.goBack()
await page.waitForTimeout(800)
console.log('   after system back: url', new URL(page.url()).pathname, '| dialog still open?', await page.getByRole('dialog').isVisible().catch(() => false))
// 2) dirty Tarjeta + system back
await page.goto(base, { waitUntil: 'networkidle' })
await page.getByRole('link', { name: 'Tarjeta' }).click()
await page.getByRole('button', { name: 'Guardar hoyo' }).waitFor()
const stepVal = async () => page.locator('[role=group]').first().innerText()
console.log('2. Tarjeta first stepper:', JSON.stringify(await stepVal()))
await page.getByRole('button', { name: /: más$/ }).first().tap()
await page.getByRole('button', { name: /: más$/ }).first().tap()
console.log('   after two taps on +:', JSON.stringify(await stepVal()))
await page.goBack()
await page.waitForTimeout(800)
console.log('   after system back: url', new URL(page.url()).pathname, '(no confirm, no blocker)')
await page.goForward()
await page.getByRole('button', { name: 'Guardar hoyo' }).waitFor()
console.log('   forward again, first stepper:', JSON.stringify(await stepVal()), '(draft gone)')
await b.close()
