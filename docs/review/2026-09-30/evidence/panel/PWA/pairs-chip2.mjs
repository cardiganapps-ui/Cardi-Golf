import { launch } from './lib.mjs'
const b = await launch()
const ctx = await b.newContext({ viewport: { width: 375, height: 667 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
await page.goto('http://127.0.0.1:4173/t/_/full12-live/juegos', { waitUntil: 'networkidle' })
const names = await page.locator('[role=tab],[role=radio]').allInnerTexts()
console.log('tabs:', JSON.stringify(names))
const t = page.locator('[role=tab],[role=radio]').filter({ hasText: /Matrimonios/ }).first()
await t.click()
await page.waitForTimeout(800)
const txt = (await page.locator('main').innerText()).replace(/\s+/g, ' ')
console.log('has pair money:', /\$[\d,]+/.test(txt), txt.match(/\$[\d,]+/g)?.slice(0, 6))
const clipped = await page.evaluate(() => [...document.querySelectorAll('*')].filter(e => e.children.length === 0 && /\$\d/.test(e.textContent) && (e.scrollWidth > e.clientWidth + 1 || e.getBoundingClientRect().right > innerWidth)).map(e => e.textContent.trim()))
console.log('clipped/overflowing money:', JSON.stringify(clipped))
