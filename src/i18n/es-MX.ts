/** "T3" → "empatado en 3.º", "3" → "3.º". Positions come from the engine as labels. */
export function ordinal(label: string): string {
  const tied = label.startsWith('T')
  const n = label.replace(/^T/, '')
  return tied ? `empatado en ${n}.º` : `${n}.º`
}

